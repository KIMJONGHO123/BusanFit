test('contract input keeps final stay and custom duration separate, validates strict inputs', () => {
  const trip = { ...initialTrip, travelDate: '2026-11-01', startTime: '09:00', endTime: '20:00' }
  const stop = { ...newStop(places[0]), stayMinutes: '100', activityCodes: ['photo', 'other'], otherMinutes: '75' }
  const input = buildDiagnosisInput(trip, [stop], policy)
  expect(input.stops[0]).toEqual({ placeId: 'test-a', plannedStaySeconds: 6000, activities: [{ code: 'photo' }, { code: 'other', durationSeconds: 4500 }] })
  expect(activitySeconds(stop, policy)).toBe(5760)
  expect(input).not.toHaveProperty('decision')
  expect(input).not.toHaveProperty('feasible')
  expect(input).toMatchObject({ timeZone: 'Asia/Seoul', transportMode: 'CAR' })
  for (const value of ['', '0', '-1', '1.5', '1e2', 'Infinity', '999999999999999999']) expect(minutesToSeconds(value)).toBeNull()
  expect(minutesToSeconds('75')).toBe(4500)
  expect(validDate('2026-02-29')).toBe(false)
  expect(validDate('2028-02-29')).toBe(true)
  for (const value of ['24:00', '9:00', '09:61']) expect(validTime(value)).toBe(false)
  expect(validateDraft({ ...trip, endTime: '09:00' }, [stop], policy)).not.toEqual([])
  expect(validateDraft(trip, [{ ...stop, visitTimeEnabled: true, plannedVisitTime: '08:59' }], policy)).not.toEqual([])
  expect(validateDraft(trip, [{ ...stop, visitTimeEnabled: true, plannedVisitTime: '20:00' }], policy)).toEqual([])
  expect(validateDraft(trip, [{ ...stop, visitTimeEnabled: true }], policy)).not.toEqual([])
  expect(buildDiagnosisInput(trip, [{ ...stop, plannedVisitTime: '08:59' }], policy).stops[0]).not.toHaveProperty('plannedVisitTime')
  expect(buildDiagnosisInput(trip, [{ ...stop, visitTimeEnabled: true, plannedVisitTime: '12:00' }], policy).stops[0]).toHaveProperty('plannedVisitTime', '12:00')
  expect(validateDraft(trip, [{ ...stop, activityCodes: ['photo', 'photo'] }], policy)).not.toEqual([])
  expect(validateDraft(trip, [{ ...stop, activityCodes: ['unknown'] }], policy)).not.toEqual([])
  expect(validateDraft(trip, [{ ...stop, otherMinutes: '0' }], policy)).not.toEqual([])
  expect(validateDraft(trip, [stop], null)).not.toEqual([])
  expect(validateDraft(trip, [stop], policy.map((p) => p.code === 'photo' ? { ...p, durationSeconds: 1200 } : p))).toEqual([])
  expect(validateDraft(trip, [stop, stop], policy)).not.toEqual([])
  expect(() => buildDiagnosisInput(trip, [newStop(places[0])], policy)).toThrow()
})

test('activity policy rejects malformed values; activity edits autofill without double counting', () => {
  expect(parseActivityPolicy(policy)).toEqual(policy)
  for (const value of [null, [], [policy[0], policy[0]], [{ ...policy[0], durationSeconds: 0 }],
    [{ ...policy[0], durationSeconds: 1.5 }], [{ ...policy[9], durationSeconds: 1800 }],
    [{ ...policy[8], durationSeconds: 1200, customDurationRequired: false }],
    [{ ...policy[0], customDurationRequired: true, durationSeconds: null }]]) expect(() => parseActivityPolicy(value)).toThrow()
  const stop = { ...newStop(places[0]), stayMinutes: '100' }
  const changed = toggleActivity(stop, 'photo', policy)
  expect(changed.stayMinutes).toBe('21')
  expect(activitySummary(changed, policy)).not.toBe(activitySummary(stop, policy))
  expect(activitySummary({ ...stop, activityCodes: ['meal'] }, policy)).not.toBe(activitySummary({ ...stop, activityCodes: ['viewing'] }, policy))
  expect(toggleActivity(changed, 'photo', policy).activityCodes).toEqual([])
  expect(toggleActivity(changed, 'photo', policy).stayMinutes).toBe('')
  const trip = { ...initialTrip, travelDate: '2026-11-01', startTime: '09:00', endTime: '20:00' }
  const restIncluded = fillStayFromActivities({ ...stop, activityCodes: ['cafe', 'meal', 'shopping', 'rest'], restMinutes: '20' }, policy)
  expect(restIncluded.stayMinutes).toBe('170')
  expect(buildDiagnosisInput(trip, [restIncluded], policy).stops[0]).toMatchObject({ plannedStaySeconds: 10200, activities: [{ code: 'cafe' }, { code: 'meal' }, { code: 'shopping' }, { code: 'rest', durationSeconds: 1200 }] })
  const restAndOther = fillStayFromActivities({ ...stop, activityCodes: ['photo', 'rest', 'other'], restMinutes: '45', otherMinutes: '75' }, policy)
  expect(restAndOther.stayMinutes).toBe('141')
  expect(buildDiagnosisInput(trip, [restAndOther], policy).stops[0]).toEqual({ placeId: 'test-a', plannedStaySeconds: 8460, activities: [{ code: 'photo' }, { code: 'rest', durationSeconds: 2700 }, { code: 'other', durationSeconds: 4500 }] })
  for (const value of ['', '0', '-1', '1.5', '1e2']) {
    const invalidRest = { ...restAndOther, restMinutes: value }
    expect(fillStayFromActivities(invalidRest, policy).stayMinutes).toBe('')
    expect(validateDraft(trip, [invalidRest], policy)).not.toEqual([])
  }
  expect(fillStayFromActivities({ ...changed, activityCodes: ['photo', 'other'], otherMinutes: '75' }, policy).stayMinutes).toBe('96')
  for (const value of ['', '0', '-1', '1.5']) expect(fillStayFromActivities({ ...changed, activityCodes: ['photo', 'other'], otherMinutes: value }, policy).stayMinutes).toBe('')
  expect(fillStayFromActivities(changed, null).stayMinutes).toBe('')
  const second = newStop(places[1])
  expect(moveStop([changed, second], 'test-a', 1)).toEqual([second, changed])
  expect(moveStop([changed, second], 'test-a', -1)).toEqual([changed, second])
})

