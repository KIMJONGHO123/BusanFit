test('a newer departure search wins over a delayed earlier response', async ({ page }) => {
  await page.route(policyEndpoint, (route) => route.fulfill({ json: policy }))
  await openPlanner(page, 1)
  await page.route('**/api/places/search?*', async (route) => {
    const keyword = new URL(route.request().url()).searchParams.get('keyword')
    if (keyword === '이전') await new Promise((resolve) => setTimeout(resolve, 250))
    await route.fulfill({ json: [keyword === '이전' ? places[0] : places[1]] }).catch(() => {})
  })
  await page.getByLabel('다른 출발지 검색').fill('이전')
  const earlierRequest = page.waitForRequest((request) => new URL(request.url()).searchParams.get('keyword') === '이전')
  await page.getByRole('button', { name: '찾기', exact: true }).click()
  await earlierRequest
  await page.getByLabel('다른 출발지 검색').fill('최신')
  await page.getByRole('button', { name: '찾기', exact: true }).click()
  await expect(page.locator('.departure-results')).toContainText('테스트 공원')
  await page.waitForTimeout(300)
  await expect(page.locator('.departure-results')).not.toContainText('테스트 해변')
})

