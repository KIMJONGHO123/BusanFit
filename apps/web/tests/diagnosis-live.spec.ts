import { test, expect } from '@playwright/test'
import { parseDiagnosis } from '../src/features/diagnosis/diagnosis'

test.skip(process.env.BUSANFIT_LIVE_WEB_DIAGNOSIS !== '1', 'Requires the isolated H2 server, explicit real API enablement and separate Vite port')

test('real browser signup, login, TourAPI search and TMAP diagnosis display partial result and allow rediagnosis', async ({ page, baseURL }, info) => {
  test.setTimeout(120000)
  // Signup is allowed only against the documented isolated H2 browser-test setup.
  expect(baseURL).toBe('http://127.0.0.1:5174')
  expect(process.env.BUSANFIT_API_TARGET).toBe('http://127.0.0.1:18080')
  await page.goto('/')
  const searchResponse = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/places/search')
  await page.getByRole('button', { name: '감천문화마을', exact: true }).click()
  expect((await searchResponse).status()).toBe(200)
  await page.getByRole('button', { name: '부산 감천문화마을 추가', exact: true }).click()
  await page.getByRole('button', { name: '순서·시간 설정', exact: true }).click()
  await page.getByLabel('여행 날짜', { exact: true }).fill('2026-11-01')
  await page.getByLabel('시작시간', { exact: true }).fill('09:00')
  await page.getByLabel('종료시간', { exact: true }).fill('18:00')
  await page.getByRole('spinbutton', { name: '부산 감천문화마을 머무를 시간 (분)' }).fill('100')
  await expect(page.getByRole('button', { name: '진단하기', exact: true })).toBeVisible()
  await page.screenshot({ path: `test-results/${info.project.name}-diagnosis-live-entry.png`, fullPage: true })
  await page.getByRole('button', { name: '진단하기', exact: true }).click()
  await page.getByRole('button', { name: '처음이신가요? 회원가입' }).click()
  await page.getByLabel('이메일', { exact: true }).fill(`task012-${info.project.name}-${Date.now()}@example.test`)
  await page.getByLabel('비밀번호', { exact: true }).fill('temporary-h2-test-password')
  await page.getByLabel('닉네임', { exact: true }).fill('웹 진단 테스트')
  const firstResponse = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v2/planner/diagnose')
  await page.getByRole('button', { name: '가입하고 진단하기', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0, { timeout: 20000 })
  const first = await firstResponse
  expect(first.status()).toBe(200)
  const result = parseDiagnosis(await first.json(), ['tourapi-1997221'])
  expect(result.decision).toMatch(/POSSIBLE|CAUTION/)
  expect(result.verificationStatus).toBe('PARTIAL')
  expect(result.schedule.totalStaySeconds).toBe(6000)
  expect(result.schedule.totalTravelSeconds).toBeGreaterThan(0)
  expect(result.schedule.requiredSeconds).toBe(6000 + result.schedule.totalTravelSeconds!)
  await expect(page.getByRole('heading', { name: '일정 진단 결과', exact: true })).toBeFocused()
  await expect(page.getByTestId('diagnosis-verdict')).toContainText('일부 확인')
  await expect(page.getByRole('heading', { name: '부산 감천문화마을', exact: true })).toBeVisible()
  const map = page.frameLocator('iframe[title="일정 경로 지도"]')
  await expect(map.locator('.place-label')).toHaveCount(2, { timeout: 30000 })
  await expect(page.getByRole('status')).toHaveCount(0, { timeout: 25000 })
  await expect(map.locator('.place-label').filter({ hasText: '부산 감천문화마을' })).toHaveCount(1)
  await map.getByRole('button', { name: '전체 경로', exact: true }).click()
  await expect.poll(() => map.locator('#map img').evaluateAll((images) => { const visible = images.filter((img) => { const r = img.getBoundingClientRect(); return r.width >= 256 && r.right > 0 && r.left < innerWidth && r.bottom > 0 && r.top < innerHeight }); return visible.length > 0 && visible.every((img) => (img as HTMLImageElement).complete && (img as HTMLImageElement).naturalWidth >= 256) }), { timeout: 20000 }).toBe(true)
  await page.locator('.route-map-shell').screenshot({ path: `test-results/${info.project.name}-diagnosis-live-map.png` })
  await page.screenshot({ path: `test-results/${info.project.name}-diagnosis-live-partial.png`, fullPage: true })
  await page.getByRole('button', { name: '일정 수정하기', exact: true }).click()
  await page.getByRole('spinbutton', { name: '부산 감천문화마을 머무를 시간 (분)' }).fill('600')
  const secondResponse = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v2/planner/diagnose')
  await page.getByRole('button', { name: '진단하기', exact: true }).click()
  const second = await secondResponse
  const adjusted = parseDiagnosis(await second.json(), ['tourapi-1997221'])
  expect(adjusted.diagnosisId).not.toBe(result.diagnosisId)
  expect(adjusted.decision).toBe('ADJUSTMENT_REQUIRED')
  expect(adjusted.verificationStatus).toBe('PARTIAL')
  expect(adjusted.schedule.totalStaySeconds).toBe(36000)
  await expect(page.getByTestId('diagnosis-verdict')).toContainText('일정을 조금 조정해 주세요')
  await expect(page.getByTestId('diagnosis-verdict')).toContainText('일부 확인')
  await page.screenshot({ path: `test-results/${info.project.name}-diagnosis-live-overrun.png`, fullPage: true })
  await info.attach('live-diagnosis-summary', { contentType: 'application/json', body: JSON.stringify({ placeId: 'tourapi-1997221', firstDecision: result.decision, verification: result.verificationStatus, travelSeconds: result.schedule.totalTravelSeconds, totalStaySeconds: result.schedule.totalStaySeconds, requiredSeconds: result.schedule.requiredSeconds, overrunDecision: adjusted.decision }) })
})
